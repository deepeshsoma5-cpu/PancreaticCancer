sec <- function(name, expr) {
  cat("\n#####", name, "#####\n")
  tryCatch(expr, error = function(e) {
    cat("SECTION FAILED:", conditionMessage(e), "\n")
    add(paste0("## ", name), "", paste0("This section failed with: ", conditionMessage(e)), "")
  })
  invisible(NULL)
}

# ---- cohorts, z scored inside each cohort, same recipe as the original scoring ----
load_cohorts <- function(drops = NULL) {
  raw <- list(GSE62452 = readRDS("data/gse62452_tumors.rds"),
              GSE21501 = readRDS("data/gse21501_tumors.rds"),
              GSE57495 = readRDS("data/fresh_gse57495.rds"))
  out <- lapply(names(raw), function(nm) {
    x <- raw[[nm]]
    keep <- colnames(x$expr)
    if (!is.null(drops) && nrow(drops) > 0) keep <- setdiff(keep, drops$sample[drops$cohort == nm])
    z <- scale(t(x$expr[, keep, drop = FALSE]))
    z[!is.finite(z)] <- 0
    list(name = nm, z = z, cl = x$clin[keep, , drop = FALSE])
  })
  names(out) <- names(raw)
  out
}

# per cohort c-index and HR per SD, plus a pooled Cox stratified by cohort
stat_set <- function(sc, ob) {
  per <- data.frame()
  P <- data.frame()
  for (nm in names(ob)) {
    cl <- ob[[nm]]$cl
    s <- sc[[nm]]
    z <- as.numeric(scale(s))
    ci <- tryCatch(cidx(s, cl$time_months, cl$status), error = function(e) NA_real_)
    f <- tryCatch(summary(coxph(Surv(cl$time_months, cl$status) ~ z)), error = function(e) NULL)
    per <- rbind(per, data.frame(cohort = nm, n = nrow(cl), events = sum(cl$status), cindex = ci,
                                 hr = if (is.null(f)) NA_real_ else f$conf.int[1, 1],
                                 lo = if (is.null(f)) NA_real_ else f$conf.int[1, 3],
                                 hi = if (is.null(f)) NA_real_ else f$conf.int[1, 4],
                                 p = if (is.null(f)) NA_real_ else f$coefficients[1, 5],
                                 stringsAsFactors = FALSE))
    P <- rbind(P, data.frame(time = cl$time_months, status = cl$status, z = z, cohort = nm,
                             stringsAsFactors = FALSE))
  }
  fp <- tryCatch(summary(coxph(Surv(time, status) ~ z + strata(cohort), data = P)), error = function(e) NULL)
  pooled <- if (is.null(fp)) rep(NA_real_, 4) else
    c(fp$conf.int[1, 1], fp$conf.int[1, 3], fp$conf.int[1, 4], fp$coefficients[1, 5])
  names(pooled) <- c("hr", "lo", "hi", "p")
  list(per = per, pooled = pooled, P = P)
}

km_rmst <- function(t, s, tau) {
  f <- survfit(Surv(t, s) ~ 1)
  i <- f$time <= tau
  tt <- c(0, f$time[i], tau)
  sv <- c(1, f$surv[i])
  sum(diff(tt) * sv)
}

