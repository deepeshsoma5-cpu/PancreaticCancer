# ---- 1. pooled individual patient analysis ----
sec("1 Pooled analysis of the three scored cohorts", {
  P <- ref$P
  P$grp <- NA_character_
  for (nm in cn) {
    i <- P$cohort == nm
    P$grp[i] <- ifelse(risk[[nm]] > median(risk[[nm]]), "high", "low")
  }
  P$grp <- factor(P$grp, levels = c("low", "high"))
  lr <- survdiff(Surv(time, status) ~ grp + strata(cohort), data = P)
  p_lr <- 1 - pchisq(lr$chisq, 1)
  hrg <- summary(coxph(Surv(time, status) ~ grp + strata(cohort), data = P))$conf.int[1, c(1, 3, 4)]

  tau <- 24
  rm_rows <- data.frame()
  for (nm in cn) {
    cl <- objs[[nm]]$cl
    hi <- risk[[nm]] > median(risk[[nm]])
    d0 <- km_rmst(cl$time_months[hi], cl$status[hi], tau) - km_rmst(cl$time_months[!hi], cl$status[!hi], tau)
    bs <- replicate(1000, {
      i <- sample(nrow(cl), replace = TRUE)
      h <- hi[i]
      if (sum(h) < 5 || sum(!h) < 5) NA_real_ else
        km_rmst(cl$time_months[i][h], cl$status[i][h], tau) - km_rmst(cl$time_months[i][!h], cl$status[i][!h], tau)
    })
    rm_rows <- rbind(rm_rows, data.frame(cohort = nm, diff = d0, se = sd(bs, na.rm = TRUE),
                                         fu_high = max(cl$time_months[hi]), fu_low = max(cl$time_months[!hi])))
  }
  w <- 1 / rm_rows$se^2
  est <- sum(w * rm_rows$diff) / sum(w)
  se_p <- sqrt(1 / sum(w))
  cat(sprintf("pooled HR per SD (stratified Cox): %.2f (%.2f-%.2f), p = %.4f\n", ref$pooled["hr"], ref$pooled["lo"], ref$pooled["hi"], ref$pooled["p"]))
  cat(sprintf("stratified log-rank p = %.4f | stratified HR high vs low %.2f (%.2f-%.2f)\n", p_lr, hrg[1], hrg[2], hrg[3]))
  cat(sprintf("RMST difference at %s months (high minus low): %.2f (%.2f to %.2f)\n", tau, est, est - 1.96 * se_p, est + 1.96 * se_p))

  png("results/42_pooled_km.png", width = 1600, height = 1200, res = 200)
  tryCatch({
    fit <- survfit(Surv(time, status) ~ grp, data = P)
    plot(fit, col = c("#1f77b4", "#d62728"), lwd = 2, xlim = c(0, 60), xlab = "months", ylab = "overall survival")
    legend("topright", legend = c("low risk", "high risk"), col = c("#1f77b4", "#d62728"), lwd = 2, bty = "n")
    title(main = "Locked signature, three external cohorts pooled",
          sub = sprintf("cohort-stratified log-rank p = %.4f, stratified HR high vs low %.2f (%.2f-%.2f)", p_lr, hrg[1], hrg[2], hrg[3]))
  }, error = function(e) cat("km plot failed:", conditionMessage(e), "\n"))
  dev.off()

  pc <- ref$per
  add("## 1. Pooled analysis of the three scored cohorts (post hoc)", "",
      mdt(data.frame(cohort = pc$cohort, n = pc$n, events = pc$events, C_index = fmt(pc$cindex),
                     HR_per_SD = paste0(fmt(pc$hr, 2), " (", fmt(pc$lo, 2), "-", fmt(pc$hi, 2), ")"), stringsAsFactors = FALSE)),
      paste0("- Individual-patient Cox model stratified by cohort, risk score z-scored within cohort: HR per SD ", fmt(ref$pooled["hr"], 2),
             " (95% CI ", fmt(ref$pooled["lo"], 2), "-", fmt(ref$pooled["hi"], 2), "), p = ", fmt(ref$pooled["p"], 4),
             ", ", sum(pc$n), " patients, ", sum(pc$events), " deaths."),
      paste0("- Within-cohort median split, cohort-stratified log-rank p = ", fmt(p_lr, 4), "; stratified HR high vs low ",
             fmt(hrg[1], 2), " (", fmt(hrg[2], 2), "-", fmt(hrg[3], 2), "). Figure: results/42_pooled_km.png."),
      paste0("- Restricted mean survival time up to ", tau, " months, high minus low risk: ", fmt(est, 2), " months (95% CI ",
             fmt(est - 1.96 * se_p, 2), " to ", fmt(est + 1.96 * se_p, 2), "), pooled by inverse variance. By cohort: ",
             paste(sprintf("%s %.2f", rm_rows$cohort, rm_rows$diff), collapse = ", "), ". Negative means high-risk patients lived fewer months."),
      if (min(rm_rows$fu_high, rm_rows$fu_low) < tau) "- Note: at least one risk group has follow-up shorter than the horizon, so the RMST for that cohort is less reliable." else NULL,
      "")
})

# ---- 2. proliferation and single gene comparators ----
sec("2 Is it just proliferation, or one gene?", {
  m <- tryCatch(msigdbr(species = "Homo sapiens", collection = "H"),
                error = function(e) msigdbr(species = "Homo sapiens", category = "H"))
  m <- as.data.frame(m)
  sets <- split(m$gene_symbol, m$gs_name)
  set_score <- function(o, nm) {
    g <- setdiff(intersect(unique(sets[[nm]]), colnames(o$z)), sig$gene)
    rowMeans(o$z[, g, drop = FALSE])
  }
  bench <- list()
  bench[["Locked 8-gene signature (reference)"]] <- risk
  bench[[paste0(top_gene, " alone (top weighted gene)")]] <- lapply(objs, function(o) as.numeric(o$z[, top_gene]))
  bench[["Unit-weight 8-gene score (signs only)"]] <- lapply(objs, function(o) as.numeric(o$z[, sig$gene, drop = FALSE] %*% sign(sig$coef)))
  bench[["Hallmark G2M checkpoint score"]] <- lapply(objs, set_score, nm = "HALLMARK_G2M_CHECKPOINT")
  bench[["Hallmark E2F targets score"]] <- lapply(objs, set_score, nm = "HALLMARK_E2F_TARGETS")
  bst <<- lapply(bench, stat_set, ob = objs)
  tb <- do.call(rbind, lapply(names(bst), function(k) {
    s <- bst[[k]]
    data.frame(score = k,
               pooled_HR_per_SD = paste0(fmt(s$pooled["hr"], 2), " (", fmt(s$pooled["lo"], 2), "-", fmt(s$pooled["hi"], 2), ")"),
               p = fmt(s$pooled["p"], 4),
               setNames(as.list(fmt(s$per$cindex, 3)), paste0("C_", s$per$cohort)),
               stringsAsFactors = FALSE, check.names = FALSE)
  }))
  print(tb, row.names = FALSE)

  adj <- function(nmset) {
    P2 <- data.frame()
    for (nm in cn) {
      o <- objs[[nm]]
      cl <- o$cl
      P2 <- rbind(P2, data.frame(time = cl$time_months, status = cl$status, cohort = nm,
                                 risk_z = as.numeric(scale(risk[[nm]])),
                                 x_z = as.numeric(scale(set_score(o, nmset))), stringsAsFactors = FALSE))
    }
    f <- summary(coxph(Surv(time, status) ~ risk_z + x_z + strata(cohort), data = P2))
    rho <- sapply(cn, function(nm) cor(P2$risk_z[P2$cohort == nm], P2$x_z[P2$cohort == nm], method = "spearman"))
    list(sig = f$conf.int["risk_z", c(1, 3, 4)], sigp = f$coefficients["risk_z", 5],
         set = f$conf.int["x_z", c(1, 3, 4)], setp = f$coefficients["x_z", 5], rho = rho)
  }
  adj_g2m <<- adj("HALLMARK_G2M_CHECKPOINT")
  adj_e2f <<- adj("HALLMARK_E2F_TARGETS")
  indep <- adj_g2m$sig[2] > 1 && adj_e2f$sig[2] > 1
  line <- function(a, lab) {
    sprintf("- Adjusted for the %s: signature HR per SD %.2f (%.2f-%.2f), p = %.4f; %s HR per SD %.2f (%.2f-%.2f), p = %.4f. Spearman correlation between signature and %s by cohort: %s.",
            lab, a$sig[1], a$sig[2], a$sig[3], a$sigp, lab, a$set[1], a$set[2], a$set[3], a$setp, lab,
            paste(sprintf("%s %.2f", cn, a$rho), collapse = ", "))
  }
  cat(line(adj_g2m, "G2M score"), "\n", line(adj_e2f, "E2F score"), "\n")
  add("## 2. Is it just proliferation, or one gene? (post hoc)", "",
      "Each comparator is scored exactly like the signature (z-scored within cohort). Hallmark scores are the mean z-score of the set genes with the 8 signature genes removed.", "",
      mdt(tb),
      line(adj_g2m, "G2M score"),
      line(adj_e2f, "E2F score"),
      if (indep) "- Verdict (rule in docs/plan_extended.md): the signature retains an association with survival beyond both proliferation scores (its adjusted HR CI is above 1 in both models)."
      else "- Verdict (rule in docs/plan_extended.md): the signature does NOT show independent information beyond proliferation in these cohorts (its adjusted HR CI includes 1 in at least one model).",
      "")
})

# ---- 3. robustness ----
sec("3 Robustness of the locked signature (no refitting)", {
  loo <- do.call(rbind, lapply(sig$gene, function(g) {
    keep <- sig$gene != g
    s <- lapply(objs, function(o) sig_score(o, sig$gene[keep], sig$coef[keep]))
    st <- stat_set(s, objs)
    data.frame(dropped_gene = g,
               pooled_HR_per_SD = paste0(fmt(st$pooled["hr"], 2), " (", fmt(st$pooled["lo"], 2), "-", fmt(st$pooled["hi"], 2), ")"),
               mean_C_index = fmt(mean(st$per$cindex, na.rm = TRUE), 3), stringsAsFactors = FALSE)
  }))
  pg <- do.call(rbind, lapply(seq_len(nrow(sig)), function(k) {
    g <- sig$gene[k]
    st <- stat_set(lapply(objs, function(o) as.numeric(o$z[, g])), objs)
    data.frame(gene = g, locked_coef = fmt(sig$coef[k], 4),
               pooled_HR_per_SD = paste0(fmt(st$pooled["hr"], 2), " (", fmt(st$pooled["lo"], 2), "-", fmt(st$pooled["hi"], 2), ")"),
               cohorts_in_coef_direction = paste0(sum((st$per$hr > 1) == (sig$coef[k] > 0), na.rm = TRUE), " of ", nrow(st$per)),
               stringsAsFactors = FALSE)
  }))
  rn_score <- function(o) {
    M <- o$z[, sig$gene, drop = FALSE]
    M <- apply(M, 2, function(v) qnorm((rank(v) - 0.5) / length(v)))
    as.numeric(M %*% sig$coef)
  }
  st_rn <- stat_set(lapply(objs, rn_score), objs)
  base_c <- mean(ref$per$cindex)
  print(loo, row.names = FALSE)
  print(pg, row.names = FALSE)
  add("## 3. Robustness of the locked signature (no refitting, post hoc)", "",
      paste0("Reference (all 8 genes, z-scoring): pooled HR per SD ", fmt(ref$pooled["hr"], 2), " (", fmt(ref$pooled["lo"], 2), "-", fmt(ref$pooled["hi"], 2),
             "), mean C-index over the three cohorts ", fmt(base_c, 3), "."), "",
      "### Leave one gene out (locked weights kept)", "", mdt(loo),
      "### Each gene alone (hazard ratio in the direction of its locked coefficient is expected)", "", mdt(pg),
      paste0("### Rank-based (inverse normal) scaling instead of z-scoring: pooled HR per SD ", fmt(st_rn$pooled["hr"], 2), " (",
             fmt(st_rn$pooled["lo"], 2), "-", fmt(st_rn$pooled["hi"], 2), "), mean C-index ", fmt(mean(st_rn$per$cindex, na.rm = TRUE), 3), "."), "")
})

# ---- 4. random signature benchmarks ----
sec("4 Random-signature benchmarks", {
  d <- readRDS("data/model_input.rds")
  gm <- d$gene_map
  in_all <- Reduce(intersect, lapply(objs, function(o) colnames(o$z)))
  poolA <- setdiff(intersect(unname(gm), in_all), sig$gene)
  tcx <- d$Xt
  tcl <- d$clin_t
  uc <- apply(tcx, 2, function(g) {
    f <- tryCatch(suppressWarnings(coxph(Surv(tcl$time_months, tcl$status) ~ g)), error = function(e) NULL)
    if (is.null(f)) c(NA_real_, NA_real_) else summary(f)$coefficients[1, c(1, 5)]
  })
  pass <- which(!is.na(uc[2, ]) & uc[2, ] < 0.01)
  cat("candidate pool A:", length(poolA), "genes | TCGA screen-passing genes:", length(pass), "(40 expected)\n")
  poolB <- data.frame(gene = unname(gm[colnames(tcx)[pass]]), sgn = sign(uc[1, pass]), stringsAsFactors = FALSE)
  poolB <- poolB[poolB$gene %in% in_all, , drop = FALSE]
  cat("screen-passing genes measured in all three cohorts:", nrow(poolB), "| locked genes among them:", sum(sig$gene %in% poolB$gene), "of", nrow(sig), "\n")
  if (length(poolA) < 50 || nrow(poolB) < 12) stop("candidate pools are too small to benchmark")

  Pb <- do.call(rbind, lapply(cn, function(nm) data.frame(time = objs[[nm]]$cl$time_months, status = objs[[nm]]$cl$status,
                                                          cohort = nm, stringsAsFactors = FALSE)))
  fast_stat <- function(sc) {
    ci <- mean(sapply(cn, function(nm) tryCatch(cidx(sc[[nm]], objs[[nm]]$cl$time_months, objs[[nm]]$cl$status),
                                                error = function(e) NA_real_)), na.rm = TRUE)
    Pb$z <- unlist(lapply(cn, function(nm) as.numeric(scale(sc[[nm]]))))
    lh <- tryCatch(unname(coef(suppressWarnings(coxph(Surv(time, status) ~ z + strata(cohort), data = Pb)))[1]),
                   error = function(e) NA_real_)
    c(cindex = ci, loghr = lh)
  }
  run_draws <- function(draw, label) {
    out <- matrix(NA_real_, nrand, 2, dimnames = list(NULL, c("cindex", "loghr")))
    for (i in seq_len(nrand)) {
      out[i, ] <- fast_stat(draw())
      if (i %% 1000 == 0) cat(label, "draws done:", i, "of", nrand, "\n")
    }
    out
  }
  drawA <- function() {
    g <- sample(poolA, 8)
    w <- sample(sig$coef)
    lapply(objs, function(o) as.numeric(o$z[, g, drop = FALSE] %*% w))
  }
  drawB <- function() {
    i <- sample(nrow(poolB), 8)
    lapply(objs, function(o) as.numeric(o$z[, poolB$gene[i], drop = FALSE] %*% poolB$sgn[i]))
  }
  sc_unit <- lapply(objs, function(o) as.numeric(o$z[, sig$gene, drop = FALSE] %*% sign(sig$coef)))
  obs_w <<- fast_stat(risk)
  obs_u <<- fast_stat(sc_unit)
  cat(sprintf("observed pooled HR per SD, weighted %.3f (stat_set gives %.3f), unit-weight %.3f\n",
              exp(obs_w["loghr"]), ref$pooled["hr"], exp(obs_u["loghr"])))
  randA <<- run_draws(drawA, "A")
  randB <<- run_draws(drawB, "B")
  write.csv(randA, "results/42_random_A.csv", row.names = FALSE)
  write.csv(randB, "results/42_random_B.csv", row.names = FALSE)

  emp <- function(rand, obs) (1 + sum(rand >= obs, na.rm = TRUE)) / (sum(!is.na(rand)) + 1)
  summ <- function(rand, obs, label) {
    data.frame(benchmark = label,
               observed_HR = fmt(exp(obs["loghr"]), 2),
               random_median_HR = fmt(exp(median(rand[, "loghr"], na.rm = TRUE)), 2),
               random_95th_percentile_HR = fmt(exp(quantile(rand[, "loghr"], 0.95, na.rm = TRUE)), 2),
               empirical_p_HR = fmt(emp(rand[, "loghr"], obs["loghr"]), 4),
               observed_mean_C = fmt(obs["cindex"], 3),
               random_median_mean_C = fmt(median(rand[, "cindex"], na.rm = TRUE), 3),
               empirical_p_C = fmt(emp(rand[, "cindex"], obs["cindex"]), 4), stringsAsFactors = FALSE)
  }
  tab <- rbind(summ(randA, obs_w, "A: random sets from the candidate pool vs locked signature"),
               summ(randB, obs_u, "B: random sets from screen-passing genes vs unit-weight signature"))
  print(tab, row.names = FALSE)
  pA <- emp(randA[, "loghr"], obs_w["loghr"])
  pB <- emp(randB[, "loghr"], obs_u["loghr"])
  verdict <- function(p) if (p < 0.05) "distinguishable from random sets" else "not distinguishable from random sets"
  add("## 4. Random-signature benchmarks (post hoc)", "",
      paste0(nrand, " random 8-gene sets per benchmark. Statistic: pooled stratified HR per SD across the three cohorts (and the mean C-index). ",
             "A: genes drawn from the ", length(poolA), "-gene candidate pool used for model building (signature genes excluded), with the 8 locked weights randomly permuted. ",
             "B: genes drawn from the ", nrow(poolB), " genes that passed the TCGA univariate screen, unit weights with the TCGA univariate sign, compared with the unit-weight version of the signature."), "",
      mdt(tab),
      paste0("- Benchmark A: the locked signature is ", verdict(pA), " from that pool (empirical p = ", fmt(pA, 4), ")."),
      paste0("- Benchmark B: the unit-weight signature is ", verdict(pB), " from the screen-passing genes (empirical p = ", fmt(pB, 4), "). This asks whether the LASSO choice of 8 genes adds anything over picking any 8 screen-passing genes."),
      "")
})

# ---- 5. sensitivity to the duplicate audit ----
sec("5 Sensitivity: drop patients flagged by the all-pairs duplicate audit", {
  dr <- read.csv("results/41_audit_drops.csv", stringsAsFactors = FALSE)
  affected <- sapply(cn, function(nm) sum(dr$sample[dr$cohort == nm] %in% rownames(objs[[nm]]$cl)))
  cat("scored patients flagged by the audit:", paste(names(affected), affected, collapse = ", "), "\n")
  if (sum(affected) == 0) {
    add("## 5. Sensitivity to the all-pairs duplicate audit", "",
        "No patient in the three scored cohorts was flagged against TCGA or against an earlier scored cohort, so no sensitivity rescore was needed.", "")
  } else {
    objs2 <- load_cohorts(dr)
    risk2 <- lapply(objs2, sig_score)
    st2 <- stat_set(risk2, objs2)
    cmp <- data.frame(cohort = cn, n_before = ref$per$n, n_after = st2$per$n,
                      C_before = fmt(ref$per$cindex), C_after = fmt(st2$per$cindex),
                      HR_before = fmt(ref$per$hr, 2), HR_after = fmt(st2$per$hr, 2), stringsAsFactors = FALSE)
    print(cmp, row.names = FALSE)
    add("## 5. Sensitivity to the all-pairs duplicate audit", "",
        paste0(sum(affected), " scored patients were flagged against TCGA or an earlier scored cohort and were removed for this rescore."), "",
